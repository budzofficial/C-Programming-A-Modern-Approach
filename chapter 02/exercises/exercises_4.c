/* Write a program that declares several int and float variables-
 * without initializing them- and then prints their values. Is there
 * any pattern to the values? (Usually there isn't)
 */

#include <stdio.h>

int main(void)
{
	int a, b;
	float x, y;

	printf("A: %d\nB: %d\nX: %f\n Y: %f\n", a, b, x, y);

	return 0;
}
